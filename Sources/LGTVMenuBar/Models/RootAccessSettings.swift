import Foundation

/// How the app reaches a root shell on a TV the owner has already rooted.
///
/// No secret lives here. The SSH private key and any password are kept in the Keychain, keyed by
/// the configuration id.
public struct RootAccessSettings: Codable, Equatable, Sendable {
    public enum Transport: String, Codable, CaseIterable, Sendable, Identifiable {
        case ssh
        case telnet

        public var id: String { rawValue }
        public var displayName: String { self == .ssh ? "SSH" : "Telnet" }
        public var defaultPort: Int { self == .ssh ? 22 : 23 }
    }

    public enum Authentication: String, Codable, CaseIterable, Sendable, Identifiable {
        /// A key pair generated by this app; the private half never leaves the Keychain.
        case appKey
        case password

        public var id: String { rawValue }
        public var displayName: String { self == .appKey ? "App Key" : "Password" }
    }

    public var isEnabled: Bool
    public var transport: Transport
    /// Empty means "the same address as the TV".
    public var hostOverride: String
    /// Nil means the transport's default port.
    public var port: Int?
    public var username: String
    public var authentication: Authentication
    /// SHA-256 fingerprint of the SSH host key accepted on first connection.
    public var trustedHostKeyFingerprint: String?

    public init(
        isEnabled: Bool = false,
        transport: Transport = .ssh,
        hostOverride: String = "",
        port: Int? = nil,
        username: String = "root",
        authentication: Authentication = .appKey,
        trustedHostKeyFingerprint: String? = nil
    ) {
        self.isEnabled = isEnabled
        self.transport = transport
        self.hostOverride = hostOverride
        self.port = port
        self.username = username
        self.authentication = authentication
        self.trustedHostKeyFingerprint = trustedHostKeyFingerprint
    }

    public var effectivePort: Int { port ?? transport.defaultPort }

    public func effectiveHost(tvAddress: String) -> String {
        let trimmed = hostOverride.trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? tvAddress : trimmed
    }

    /// True when shell access points somewhere other than the TV being controlled.
    public func usesDifferentHost(than tvAddress: String) -> Bool {
        effectiveHost(tvAddress: tvAddress) != tvAddress
    }
}
